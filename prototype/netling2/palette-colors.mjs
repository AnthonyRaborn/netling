// Computes the recolorable wearables' automatic colours for the new palettes (palettes.js) with tools/wearable-colors.mjs's own method and
// writes prototype/netling2/palette-colors.js, which the browser can load (the tool itself needs node). Run after changing the palettes,
// the sprites or a recolorable wearable; palettes.test.js fails when the file is out of date.
//   node prototype/netling2/palette-colors.mjs           print
//   node prototype/netling2/palette-colors.mjs --write   rewrite palette-colors.js
import './ready.js';
import { writeFileSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { registerIdeas } from './accessory-ideas.js';
import { PALETTES } from '../../src/sim.js';
import { computeAutoColors } from '../../tools/wearable-colors.mjs';
import { NEW_PALETTES, addPalettes } from './palettes.js';

export function computeNewColors() {
  registerIdeas();
  addPalettes();
  const { out } = computeAutoColors();
  const table = {};
  for (const [id, slots] of Object.entries(out)) table[id] = slots.map((byPalette) => Object.fromEntries(NEW_PALETTES.map((p) => [p.name, byPalette[p.name]])));
  return table;
}
export function render(table) {
  const lines = ['// Generated by prototype/netling2/palette-colors.mjs: do not edit by hand. The automatic colours of each recolorable wearable (1.0\'s and the style ideas\')',
    '// for the new palettes in palettes.js, as src/wearable-colors.js has them for the six.', 'export const NEW_AUTO_COLORS = {'];
  for (const [id, slots] of Object.entries(table)) {
    lines.push(`  '${id}': [`);
    for (const slot of slots) lines.push(`    { ${Object.entries(slot).map(([p, c]) => `${p}: '${c}'`).join(', ')} },`);
    lines.push('  ],');
  }
  lines.push('};', '');
  return lines.join('\n');
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = render(computeNewColors());
  if (process.argv.includes('--write')) {
    writeFileSync(fileURLToPath(new URL('./palette-colors.js', import.meta.url)), text);
    console.log(`wrote palette-colors.js (${PALETTES.length} palettes loaded)`);
  } else console.log(text);
}
